import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { PDFDocument, StandardFonts } from 'pdf-lib';
import { mkdir } from 'node:fs/promises';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3000';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.waitForSelector('.recent-disputes');
  await page.screenshot({ path: 'artifacts/overview-desktop.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.body.scrollWidth), 1440);
  await page.getByRole('button', { name: 'New dispute', exact: true }).click();
  await page.locator('.bureau-choice').nth(0).click();
  await page.locator('.bureau-choice').nth(3).click();
  await page.screenshot({ path: 'artifacts/dispute-builder.png' });
  await page.locator('.wizard-footer button[type="submit"]').click();
  await page.locator('#new-creditor').fill('Test Credit Union');
  await page.locator('#new-account').fill('4321');
  await page.locator('#new-details').fill('Fictional UI test: the statement shows a balance of $250, while the report shows $450. Please investigate this discrepancy and correct the reported balance.');
  await page.locator('.wizard-footer button[type="submit"]').click();
  await page.locator('.check-label input').check();
  await page.getByRole('button', { name: 'Create dispute draft' }).click();
  await page.waitForSelector('.modal-paper--drawer');
  assert.equal(await page.locator('.modal-header h2').innerText(), 'Test Credit Union');
  await page.getByRole('button', { name: 'Edit draft', exact: true }).click();
  await page.locator('#edit-details').fill('Updated fictional test: my account statement shows $250, but the credit report shows $450. Please correct the balance after reviewing the relevant account records.');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.detail-explanation p')?.textContent.includes('Updated fictional test'));
  const [letter] = await Promise.all([page.waitForEvent('download'), page.getByRole('link', { name: 'Download draft', exact: true }).click()]);
  assert.ok(letter.suggestedFilename().includes('experian-dispute-draft'));
  await page.locator('.detail-tabs .tab').nth(2).click();
  await page.getByRole('button', { name: 'Add document', exact: true }).click();
  await page.waitForSelector('.drop-zone');
  const pdf = await PDFDocument.create(); const pdfPage = pdf.addPage(); const font = await pdf.embedFont(StandardFonts.Helvetica); pdfPage.drawText('Fictional browser test evidence, already redacted.', { font });
  await page.locator('#upload-file').setInputFiles({ name: 'UI test evidence.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await pdf.save()) });
  await page.locator('.check-label input').check();
  await page.getByRole('button', { name: 'Upload document', exact: true }).click();
  await page.waitForSelector('.modal-paper--drawer');
  await page.getByRole('button', { name: 'Record submission', exact: true }).click();
  await page.locator('#submission-reference').fill('FICTIONAL-UI-001');
  await page.locator('.inline-action-form .check-label input').check();
  await page.getByRole('button', { name: 'Record submission', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.detail-status-row .status-badge')?.textContent.includes('In review'));
  await page.getByRole('button', { name: 'Update outcome', exact: true }).click();
  await page.locator('#response-notes').fill('Fictional UI result: corrected balance confirmed.');
  await page.getByRole('button', { name: 'Save response', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.detail-status-row .status-badge')?.textContent.includes('Resolved'));
  await page.screenshot({ path: 'artifacts/dispute-detail.png' });
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.locator('.sidebar .nav-item').filter({ hasText: 'My disputes' }).click();
  await page.getByLabel('Filter by bureau').selectOption('innovis');
  assert.equal(await page.locator('.dispute-table tbody tr').count(), 1);
  await page.locator('.sidebar .nav-item').filter({ hasText: 'Credit reports' }).click();
  assert.equal(await page.locator('.report-card').count(), 4);
  await page.locator('.sidebar .nav-item').filter({ hasText: 'Documents' }).click();
  await page.getByRole('button', { name: 'Delete UI test evidence.pdf' }).click();
  await page.getByRole('button', { name: 'Remove document', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.modal-backdrop'));
  await page.getByLabel('Search your workspace').fill('Test Credit');
  await page.waitForSelector('.search-results');
  assert.equal(await page.locator('.search-results button').count(), 2);
  await page.locator('.search-results button').first().click();
  await page.waitForSelector('.modal-paper--drawer');
  await page.keyboard.press('Escape');
  await page.locator('.sidebar .nav-item').filter({ hasText: 'Learning center' }).click();
  await page.locator('.article-card').first().click();
  await page.waitForSelector('.article-content');
  await page.keyboard.press('Escape');
  await page.locator('.faq-row button').first().click();
  assert.ok((await page.locator('.faq-row p').innerText()).includes('official bureau'));
  await page.locator('.sidebar .nav-item').filter({ hasText: 'Settings' }).click();
  await page.locator('#profile-name').fill('Jamie Example');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await page.waitForFunction(() => document.querySelector('.profile-name strong')?.textContent === 'Jamie Example');
  await page.getByRole('button', { name: 'Help & support' }).click();
  await page.waitForSelector('.help-body');
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const phone = await mobile.newPage();
  await phone.goto(base, { waitUntil: 'networkidle' });
  await phone.waitForSelector('.recent-disputes');
  assert.equal(await phone.evaluate(() => document.body.scrollWidth), 390);
  await phone.screenshot({ path: 'artifacts/overview-mobile.png', fullPage: true });
  await phone.getByRole('button', { name: 'Open navigation' }).click();
  await phone.locator('.sidebar .nav-item').filter({ hasText: 'My disputes' }).click();
  await phone.waitForSelector('.dispute-summary');
  assert.equal(await phone.evaluate(() => document.body.scrollWidth), 390);
  await phone.getByRole('button', { name: 'New dispute', exact: true }).click();
  await phone.waitForSelector('.bureau-selection-grid');
  assert.equal(await phone.evaluate(() => document.body.scrollWidth), 390);
  await phone.waitForTimeout(300);
  const dialogBounds = await phone.locator('.modal-paper').boundingBox();
  assert.ok(dialogBounds.x >= 0 && dialogBounds.x + dialogBounds.width <= 390, 'Mobile dialog stays inside the visual viewport');
  await phone.screenshot({ path: 'artifacts/mobile-dialog-fixed.png' });
  await phone.getByRole('button', { name: 'Close dialog' }).click();
  await mobile.close();
  console.log('PASS: desktop/mobile layouts, guided drafts, edit, PDF download, upload/delete, submission/result tracking, bureau filtering, reports, global search, guides, profile, and support. No browser exceptions.');
} finally { await browser.close(); }
